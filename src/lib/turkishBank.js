const CATEGORY_GROUPS = {
  science: ['science', 'technology', 'space'],
  history: ['history'],
  geography: ['geography'],
  arts_and_literature: ['arts_and_literature'],
  film_and_tv: ['film_and_tv'],
  music: ['music'],
  sport_and_leisure: ['sport_and_leisure'],
  food_and_drink: ['food_and_drink'],
  general_knowledge: ['general_knowledge'],
}

function shuffle(list) {
  const copy = [...list]
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

export function turkishQuestions({ category = 'any', difficulty = 'any', amount = 10 } = {}) {
  const groups = CATEGORY_GROUPS[category]
  let pool = turkishBank.filter((q) => (groups ? groups.includes(q.category) : true))

  if (difficulty !== 'any') {
    const byDifficulty = pool.filter((q) => q.difficulty === difficulty)
    if (byDifficulty.length >= 3) pool = byDifficulty
  }
  if (pool.length < 3) pool = turkishBank

  return shuffle(pool)
    .slice(0, Math.max(3, Math.min(amount, pool.length)))
    .map((q) => {
      const options = shuffle(q.answers.map((text, i) => ({ text, correct: i === q.correctIndex })))
      return {
        id: `tr-bank:${q.id}`,
        question: q.question,
        answers: options.map((o) => o.text),
        correctIndex: options.findIndex((o) => o.correct),
        category: q.category,
        difficulty: q.difficulty,
        source: 'tr-bank',
      }
    })
}
